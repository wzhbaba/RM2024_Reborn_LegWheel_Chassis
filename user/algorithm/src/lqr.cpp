void Lqr::Calc() {
  //ll, lr, ll^2, ll*lr, lr^2, ll^3, ll^2*lr, ll*lr^2, lr^3
  float l[9] = { 0 };
  l[0] = leg_len_l_;
  l[1] = leg_len_r_;
  l[2] = leg_len_l_ * leg_len_l_;
  l[3] = leg_len_l_ * leg_len_r_;
  l[4] = leg_len_r_ * leg_len_r_;
  l[5] = leg_len_l_ * leg_len_l_ * leg_len_l_;
  l[6] = leg_len_l_ * leg_len_l_ * leg_len_r_;
  l[7] = leg_len_l_ * leg_len_r_ * leg_len_r_;
  l[8] = leg_len_r_ * leg_len_r_ * leg_len_r_;

  //计算当前腿长下的lqrK增益矩阵
  //顺序是T_wl, T_ll, T_wr, T_lr各12组依次排列
  //状态顺序: [x, dot_x, yaw, dot_yaw, roll, dot_roll, theta_l, dot_theta_l, theta_r, dot_theta_r, phi, dot_phi]
  for (uint8_t i = 0; i < 4; ++i) {
    uint8_t j = i * 12;
    T_K_[i][0] =
      (k[j + 0][0] * l[0] + k[j + 0][1] * l[1] + k[j + 0][2] * l[2] + k[j + 0][3] * l[3] +
       k[j + 0][4] * l[4] + k[j + 0][5] * l[5] + k[j + 0][6] * l[6] +
       k[j + 0][7] * l[7] + k[j + 0][8] * l[8] + k[j + 0][9] * l[9]) * dist_;
    T_K_[i][1] =
      (k[j + 1][0] * l[0] + k[j + 1][1] * l[1] + k[j + 1][2] * l[2] + k[j + 1][3] * l[3] +
       k[j + 1][4] * l[4] + k[j + 1][5] * l[5] + k[j + 1][6] * l[6] +
       k[j + 1][7] * l[7] + k[j + 1][8] * l[8] + k[j + 1][9] * l[9]) * (target_speed_ - speed_);
    T_K_[i][2] =
      (k[j + 2][0] * l[0] + k[j + 2][1] * l[1] + k[j + 2][2] * l[2] + k[j + 2][3] * l[3] +
       k[j + 2][4] * l[4] + k[j + 2][5] * l[5] + k[j + 2][6] * l[6] +
       k[j + 2][7] * l[7] + k[j + 2][8] * l[8] + k[j + 2][9] * l[9]) * (target_yaw_ - yaw_);
    T_K_[i][3] =
      (k[j + 3][0] * l[0] + k[j + 3][1] * l[1] + k[j + 3][2] * l[2] + k[j + 3][3] * l[3] +
       k[j + 3][4] * l[4] + k[j + 3][5] * l[5] + k[j + 3][6] * l[6] +
       k[j + 3][7] * l[7] + k[j + 3][8] * l[8] + k[j + 3][9] * l[9]) * (target_w_yaw_ - w_yaw_);
    T_K_[i][4] =
      (k[j + 4][0] * l[0] + k[j + 4][1] * l[1] + k[j + 4][2] * l[2] + k[j + 4][3] * l[3] +
       k[j + 4][4] * l[4] + k[j + 4][5] * l[5] + k[j + 4][6] * l[6] +
       k[j + 4][7] * l[7] + k[j + 4][8] * l[8] + k[j + 4][9] * l[9]) * roll_;
    T_K_[i][5] =
      (k[j + 5][0] * l[0] + k[j + 5][1] * l[1] + k[j + 5][2] * l[2] + k[j + 5][3] * l[3] +
       k[j + 5][4] * l[4] + k[j + 5][5] * l[5] + k[j + 5][6] * l[6] +
       k[j + 5][7] * l[7] + k[j + 5][8] * l[8] + k[j + 5][9] * l[9]) * w_roll_;
    T_K_[i][6] =
      (k[j + 6][0] * l[0] + k[j + 6][1] * l[1] + k[j + 6][2] * l[2] + k[j + 6][3] * l[3] +
       k[j + 6][4] * l[4] + k[j + 6][5] * l[5] + k[j + 6][6] * l[6] +
       k[j + 6][7] * l[7] + k[j + 6][8] * l[8] + k[j + 6][9] * l[9]) * theta_l_;
    T_K_[i][7] =
      (k[j + 7][0] * l[0] + k[j + 7][1] * l[1] + k[j + 7][2] * l[2] + k[j + 7][3] * l[3] +
       k[j + 7][4] * l[4] + k[j + 7][5] * l[5] + k[j + 7][6] * l[6] +
       k[j + 7][7] * l[7] + k[j + 7][8] * l[8] + k[j + 7][9] * l[9]) * w_theta_l;
    T_K_[i][8] =
      (k[j + 8][0] * l[0] + k[j + 8][1] * l[1] + k[j + 8][2] * l[2] + k[j + 8][3] * l[3] +
       k[j + 8][4] * l[4] + k[j + 8][5] * l[5] + k[j + 8][6] * l[6] +
       k[j + 8][7] * l[7] + k[j + 8][8] * l[8] + k[j + 8][9] * l[9]) * theta_r_;
    T_K_[i][9] =
      (k[j + 9][0] * l[0] + k[j + 9][1] * l[1] + k[j + 9][2] * l[2] + k[j + 9][3] * l[3] +
       k[j + 9][4] * l[4] + k[j + 9][5] * l[5] + k[j + 9][6] * l[6] +
       k[j + 9][7] * l[7] + k[j + 9][8] * l[8] + k[j + 9][9] * l[9]) * w_theta_r;
    T_K_[i][10] =
      (k[j + 10][0] * l[0] + k[j + 10][1] * l[1] + k[j + 10][2] * l[2] + k[j + 10][3] * l[3] +
       k[j + 10][4] * l[4] + k[j + 10][5] * l[5] + k[j + 10][6] * l[6] +
       k[j + 10][7] * l[7] + k[j + 10][8] * l[8] + k[j + 10][9] * l[9]) * phi_;
    T_K_[i][11] =
      (k[j + 11][0] * l[0] + k[j + 11][1] * l[1] + k[j + 11][2] * l[2] + k[j + 11][3] * l[3] +
       k[j + 11][4] * l[4] + k[j + 11][5] * l[5] + k[j + 11][6] * l[6] +
       k[j + 11][7] * l[7] + k[j + 11][8] * l[8] + k[j + 11][9] * l[9]) * w_phi_;
  }
  //离地时，仅对髋关节计算theta和theta_dot
  if (F_N_ < 20.0f) {
    for (uint8_t i = 0; i < 6; ++i) {
      //轮力矩置零
      T_K_[0][i] = 0.0f;
      T_K_[2][i] = 0.0f;
    };
    T_K_[1][2] = T_K_[1][3] = T_K_[1][4] = T_K_[1][5] = 0.0f;
  }
  //正常情况，计算T和Tp
  for (uint8_t i = 0; i < 4; ++i) {
    T_[i] = T_K_[i][0] + T_K_[i][1] + T_K_[i][2] + T_K_[i][3] + T_K_[i][4] +
      T_K_[i][5] + T_K_[i][6] + T_K_[i][7] + T_K_[i][8] + T_K_[i][9] +
      T_K_[i][10] + T_K_[i][11];
  }
}